/* 
 * 1)bitAnd - x&y using only ~ and | 
 *   Example: bitAnd(6, 5) = 4
 *   Legal ops: ~ |
 *   Max ops: 8
 *   Rating: 1
 */
int bitAnd(int x, int y) {
  return ~(~x | ~y);
}
/* 
 * 2)evenBits - return word with all even-numbered bits set to 1
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 8
 *   Rating: 1
 */
int evenBits(void) { 
  int word;

  word = 0x55;
  word = word << 8;
  word = word | 0x55;
  word = word << 8;
  word = word | 0x55;
  word = word << 8;
  word = word | 0x55;

  return word;
}

/*
 * 3)isTmin - returns 1 if x is the minimum two's complement number
 *     and 0 otherwise 
 *   Legal ops: ! ~ & ^ | +
 *   Max ops: 10
 *   Rating: 1
 */
int isTmin(int x) {
  return !((x^(~x+1))+!x) ;
}
/* 
 * 4)allEvenBits - return 1 if all even-numbered bits in word set to 1
 *   Examples allEvenBits(0xFFFFFFFE) = 0, allEvenBits(0x55555555) = 1
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 12
 *   Rating: 2
 */
int allEvenBits(int x) {
  int mask;

  mask = ~((0x55 << 24) | (0x55 << 16) | (0x55 << 8) | (0x55));
  x = x | mask;

  return !(~x);
}
/* 
 * 5)getByte - Extract byte n from word x
 *   Bytes numbered from 0 (LSB) to 3 (MSB)
 *   Examples: getByte(0x12345678,1) = 0x56
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 6
 *   Rating: 2
 */
int getByte(int x, int n) {
  int extract;

  extract = x;
  n = n << 3;
  extract = extract >> n;
  extract = extract & 0xff;
  
  return extract;
}
