/* 
 * 7)conditional - same as x ? y : z 
 *   Example: conditional(2,4,5) = 4
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 16
 *   Rating: 3
 */
int conditional(int x, int y, int z) { 
  int c;
  int t;
  int f;

  c = (!x);
  t = ~c + 1; 
  f = ~t; 

  return (z & t) + (y & f); 
}
/*
 * 8)ezThreeFourths - multiplies by 3/4 rounding toward 0,
 *   Should exactly duplicate effect of C expression (x*3/4),
 *   including overflow behavior.
 *   Examples: ezThreeFourths(11) = 8
 *             ezThreeFourths(-9) = -6
 *             ezThreeFourths(1073741824) = -268435456 (overflow)
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 12
 *   Rating: 3
 */
int ezThreeFourths(int x) {  
  int adjforneg;

  x = x + x + x;

  adjforneg = (x >> 31);
  adjforneg = 0x3 & adjforneg; //For rounding when the input is negative as suggested on Piazza

  return (x + adjforneg) >> 2;
}  
