/* 
 * 10)isNonZero - Check whether x is nonzero using
 *              the legal operators except !
 *   Examples: isNonZero(3) = 1, isNonZero(0) = 0
 *   Legal ops: ~ & ^ | + << >>
 *   Max ops: 10
 *   Rating: 4 
 */
int isNonZero(int x) {
  return ((x | (~x + 1)) >> 31) & 1;
}
/*
 * 11)leftBitCount - returns count of number of consective 1's in
 *     left-hand (most significant) end of word.
 *   Examples: leftBitCount(-1) = 32, leftBitCount(0xFFF0F0F0) = 12
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 50
 *   Rating: 4
 */
int leftBitCount(int x) {
  int n;
  int onemask;
  int currentmask;

  x = ~x;

  n = 0;
  onemask = 0xFF + (0xFF << 8);
  currentmask = (x >> 16) & (onemask);

  n += (!currentmask) << 4;
  x =  x >> ((!!currentmask) << 4);

  currentmask = (x >> 8) & (0xFF);
  n += (!currentmask) << 3;
  x = x >> ((!!currentmask) << 3);

  currentmask = (x >> 4) & (0xF);
  n += (!currentmask) << 2;
  x = x >> ((!!currentmask) << 2);

  currentmask = (x >> 2) & (0x3);
  n += (!currentmask) << 1;
  x = x >> ((!!currentmask) << 1);

  currentmask = (x >> 1) & (0x1);
  n += (!currentmask);
  x = x >> (!!currentmask);

  currentmask = (x) & (0x1);
  n += (!currentmask);

  return n;
}
/*
 * 12)trueThreeFourths - multiplies by 3/4 rounding toward 0,
 *   avoiding errors due to overflow
 *   Examples: trueThreeFourths(11) = 8
 *             trueThreeFourths(-9) = -6
 *             trueThreeFourths(1073741824) = 805306368 (no overflow)
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 20
 *   Rating: 4
 */
int trueThreeFourths(int x) { 
  int adjforneg = 0;

  int quotient = x >> 2;
  int remainder = x & 0x3;
  quotient = quotient + quotient + quotient;
  remainder = remainder + remainder + remainder;

  adjforneg = (x >> 31) & 0x3; //For rounding when the input is negative as suggested on Piazza

  return quotient + ((remainder + adjforneg) >> 2);
}
